#!/usr/bin/env node
/*
 * Mindlines Substack sync
 * -----------------------
 * Fetches the public Substack RSS feed and writes a local snapshot to
 * substack-articles.js. The site then reads that snapshot, so the Notes
 * page works on static hosting without CORS issues or a backend.
 *
 * This runs automatically via .github/workflows/sync-substack.yml. It can
 * also be run manually to refresh immediately:
 *
 *   node sync-substack.js
 *
 * Only published posts are stored; future-dated (scheduled) posts are
 * dropped. The Notes page displays the 2026 LifeNotes post and anything
 * published after it (see main.js).
 */

const fs = require('fs');
const path = require('path');

const FEED_URL = 'https://mindlines.substack.com/feed';
const OUT_FILE = path.join(__dirname, 'substack-articles.js');

const NAMED_ENTITIES = {
  amp: '&',
  lt: '<',
  gt: '>',
  quot: '"',
  apos: "'",
  nbsp: '\u00a0',
  hellip: '\u2026',
  mdash: '\u2014',
  ndash: '\u2013',
  lsquo: '\u2018',
  rsquo: '\u2019',
  ldquo: '\u201c',
  rdquo: '\u201d'
};

function decodeEntities(value) {
  return String(value)
    .replace(/&#x([0-9a-f]+);/gi, (_, hex) => String.fromCodePoint(parseInt(hex, 16)))
    .replace(/&#(\d+);/g, (_, dec) => String.fromCodePoint(parseInt(dec, 10)))
    .replace(/&([a-z][a-z0-9]+);/gi, (match, name) => {
      const decoded = NAMED_ENTITIES[name.toLowerCase()];
      return decoded === undefined ? match : decoded;
    });
}

function extractTag(block, tagName) {
  const pattern = new RegExp('<' + tagName + '(?:\\s[^>]*)?>([\\s\\S]*?)<\\/' + tagName + '>', 'i');
  const match = block.match(pattern);
  if (!match) return '';
  let value = match[1].trim();
  const cdata = value.match(/^<!\[CDATA\[([\s\S]*?)\]\]>$/);
  if (cdata) value = cdata[1];
  return value;
}

function extractAttribute(block, tagName, attribute) {
  const pattern = new RegExp('<' + tagName + '\\b[^>]*\\b' + attribute + '\\s*=\\s*(["\'])([\\s\\S]*?)\\1', 'i');
  const match = block.match(pattern);
  return match ? match[2] : '';
}

function slugFromUrl(url) {
  const match = String(url).match(/\/p\/([^/?#]+)/i);
  return match ? match[1] : '';
}

function formatDate(raw) {
  const date = new Date(raw);
  if (Number.isNaN(date.getTime())) return { iso: '', label: '' };
  return {
    iso: date.toISOString(),
    label: date.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' })
  };
}

function parseFeed(xml) {
  const items = xml.match(/<item\b[\s\S]*?<\/item>/gi) || [];
  return items.map(block => {
    const title = decodeEntities(extractTag(block, 'title')).trim();
    const link = extractTag(block, 'link').trim();
    const description = decodeEntities(extractTag(block, 'description')).trim();
    const content = extractTag(block, 'content:encoded');
    const pubDate = extractTag(block, 'pubDate').trim();
    const author = decodeEntities(extractTag(block, 'dc:creator')).trim();
    const image = extractAttribute(block, 'enclosure', 'url');
    const date = formatDate(pubDate);
    const contentText = decodeEntities(content.replace(/<[^>]+>/g, ' ')).replace(/\s+/g, ' ').trim();

    return {
      slug: slugFromUrl(link),
      title,
      description,
      url: link,
      author,
      image,
      dateISO: date.iso,
      dateLabel: date.label,
      content,
      hasFullContent: contentText.length >= 200
    };
  }).filter(item => item.slug && item.title && item.dateISO && Date.parse(item.dateISO) <= Date.now());
}

async function main() {
  console.log('Fetching ' + FEED_URL + ' ...');
  const response = await fetch(FEED_URL, {
    headers: { 'user-agent': 'Mozilla/5.0 (compatible; MindlinesSync/1.0)' }
  });
  if (!response.ok) {
    throw new Error('Feed request failed with status ' + response.status);
  }

  const xml = await response.text();
  const articles = parseFeed(xml);
  if (!articles.length) {
    throw new Error('No articles found in the feed.');
  }

  const header = [
    '/*',
    ' * Auto-generated by sync-substack.js. Do not edit by hand.',
    ' * Source: ' + FEED_URL,
    ' */',
    ''
  ].join('\n');

  const output = header + 'window.SUBSTACK_ARTICLES = ' + JSON.stringify(articles, null, 2) + ';\n';
  if (fs.existsSync(OUT_FILE) && fs.readFileSync(OUT_FILE, 'utf8') === output) {
    console.log('No changes; ' + path.basename(OUT_FILE) + ' is already up to date.');
    return;
  }
  fs.writeFileSync(OUT_FILE, output, 'utf8');
  console.log('Wrote ' + articles.length + ' articles to ' + path.basename(OUT_FILE));
}

main().catch(error => {
  console.error('Sync failed: ' + error.message);
  process.exitCode = 1;
});
